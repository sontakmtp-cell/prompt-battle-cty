import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { RULESET } from "@prompt-chien/contracts";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const read = relative => readFileSync(`${root}${relative}`, "utf8").replace(/\r\n/g, "\n");

const extApps = readFileSync(require.resolve("@modelcontextprotocol/ext-apps/app-with-deps"), "utf8")
  .replace(/export\{([^}]+)\};?\s*$/, (_, body) => {
    const fields = body.split(",").map(pair => pair.trim()).filter(Boolean).map(pair => {
      const [local, exported] = pair.split(" as ").map(value => value.trim());
      return `${JSON.stringify(exported ?? local)}:${local}`;
    });
    return `globalThis.ExtApps={${fields.join(",")}};`;
  });

function browserModule(relative) {
  return read(relative)
    .replace(/^import[^;]+;\s*/gm, "")
    .replace(/^export\s+/gm, "");
}

const viewerBundle = `globalThis.PromptChienViewer=(()=>{
const RULESET=${JSON.stringify(RULESET)};
${browserModule("packages/ui/dist/directions.js")}
${browserModule("packages/ui/dist/palette.js")}
${browserModule("packages/ui/dist/view.js")}
${browserModule("packages/ui/dist/render.js")}
return { drawViewer, viewCheckpoint, captionEvent };
})();`;

const bundle = (source, extras = []) => extras.reduce(
  (html, [marker, value]) => html.replace(marker, () => value),
  read(source).replace("/*__EXT_APPS_BUNDLE__*/", () => extApps),
).replace(/<\/script/gi, "<\\/script");

const html = bundle("apps/api/src/m4-widget.html", [["/*__PROMPT_CHIEN_VIEWER__*/", viewerBundle]]);
const gameHtml = read("apps/web/index.html")
  .replaceAll('="/', '="https://api.kythuatvang.com/panel/')
  .replaceAll('": "/pkg/', '": "https://api.kythuatvang.com/panel/pkg/')
  .replace('<script src="https://api.kythuatvang.com/panel/runtime-config.js"></script>', '<script>window.PROMPTCHIEN_API_BASE="https://api.kythuatvang.com";</script>');

writeFileSync(`${root}apps/api/src/m4-widget.mjs`, `// Generated by tools/build-m4-widget.mjs.\nexport const M4_WIDGET_HTML = ${JSON.stringify(html)};\n`);
writeFileSync(`${root}apps/api/src/m4-game-widget.mjs`, `// Generated by tools/build-m4-widget.mjs.\nexport const M4_GAME_WIDGET_HTML = ${JSON.stringify(gameHtml)};\n`);
console.log(`M4 widget built (${Buffer.byteLength(html)} bytes)`);
